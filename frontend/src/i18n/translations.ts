// Capitalize the first letter of a word (e.g. 'adult' -> 'Adult'),
// used to turn backend enum values into translation keys.
export function capitalize(word: string): string {
  if (!word) return word
  return word.charAt(0).toUpperCase() + word.slice(1)
}

